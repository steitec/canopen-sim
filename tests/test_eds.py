"""EDS export, verified by importing with python canopen."""
import io

import canopen
import pytest

from canopen_sim.eds import export_eds
from canopen_sim.od import DataType
from canopen_sim.profile import build_node, bundled_profiles

NODE_ID = 9


def _import(text, node_id=NODE_ID):
    stream = io.StringIO(text)
    stream.name = "node.eds"  # canopen picks the format from the file name
    return canopen.import_od(stream, node_id)


def _expected_default(var, defaults):
    value = defaults[(var.index, var.sub)]
    if var.dtype == DataType.OCTET_STRING:
        return bytes(value)
    if var.dtype == DataType.REAL32:
        return pytest.approx(value)
    return int(value) if not isinstance(value, (str, bytes)) else value


@pytest.mark.parametrize("name", bundled_profiles())
def test_eds_imports_with_canopen(name):
    node = build_node(name, node_id=NODE_ID)
    text = export_eds(node)
    assert text.startswith("; Generated by canopen-sim; checked by importing with python canopen, not against CiA 306")
    od = _import(text)
    assert od.device_information.product_name == name
    assert od.device_information.simple_boot_up_slave
    assert {125000, 250000, 500000, 1000000} <= od.device_information.allowed_baudrates
    for var in node.od.entries():
        obj = od[var.index]
        got = obj if var.sub == 0 and not hasattr(obj, "subindices") else obj[var.sub]
        assert got.data_type == int(var.dtype), (var.index, var.sub)
        assert got.access_type == var.access, (var.index, var.sub)
        assert got.pdo_mappable == var.pdo_mappable, (var.index, var.sub)
        assert got.default == _expected_default(var, node._defaults), (var.index, var.sub)
        if var.low is not None and var.dtype not in (DataType.REAL32,):
            assert got.min == var.low
        if var.high is not None and var.dtype not in (DataType.REAL32,):
            assert got.max == var.high


def test_eds_roundtrip_values():
    od = _import(export_eds(build_node("generic-drive", node_id=NODE_ID)))
    status = od[0x6041]
    assert status.data_type == int(DataType.UNSIGNED16)
    assert status.access_type == "ro" and status.pdo_mappable
    target = od[0x60FF]
    assert target.data_type == int(DataType.INTEGER32)
    assert target.access_type == "rw" and target.pdo_mappable


def test_eds_node_id_relative_cob_ids():
    text = export_eds(build_node("generic-io", node_id=5))
    assert "$NODEID+0x80" in text
    od = _import(text, node_id=33)
    assert od[0x1014].default == 0x80 + 33
    assert od[0x1200][1].default == 0x600 + 33
    assert od[0x1200][2].default == 0x580 + 33


def test_eds_is_deterministic_and_written_to_file(tmp_path):
    node = build_node("generic-io", node_id=3)
    path = tmp_path / "io.eds"
    text = export_eds(node, path)
    assert path.read_text(encoding="utf-8") == text
    assert export_eds(node) == text
    assert "FileName=generic-io.eds" in text


def test_eds_uses_defaults_not_runtime_state():
    node = build_node("generic-io", node_id=3)
    before = export_eds(node)
    node.od.set(0x1017, 0, 777)
    assert export_eds(node) == before
