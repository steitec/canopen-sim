"""Export a node's object dictionary as an EDS (INI) file.

The layout is written from our own object dictionary and from what the
``canopen`` Python library's importer reads. It is *not* checked against
CiA 306 (members-only); the tests validate it by importing it again.

Choices made here:

* An object with only sub-index 0 is a VAR (0x7); every object with more
  sub-indexes is a RECORD (0x9), even if all its entries share a type.
* Values are the node's profile defaults (the snapshot taken at construction),
  never the live runtime state, so an export is reproducible.
* COB-IDs equal to a pre-defined base plus the node ID are written as
  ``$NODEID+0x...`` so the file also works for other node IDs.
* No creation date is written unless ``created`` is passed, keeping the
  output deterministic.
* Text containing ``;`` or a line break cannot be represented (the importer
  treats ``;`` as a comment) and raises ``ValueError``.
"""
from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import TYPE_CHECKING, Any

from .od import DataType, Variable

if TYPE_CHECKING:
    from .node import Node

HEADER = "; Generated by canopen-sim; checked by importing with python canopen, not against CiA 306"

_MANDATORY = (0x1000, 0x1001, 0x1018)
_SIGNED_BITS = {DataType.INTEGER8: 8, DataType.INTEGER16: 16,
                DataType.INTEGER32: 32, DataType.INTEGER64: 64}
_BITS = {DataType.BOOLEAN: 8, DataType.UNSIGNED8: 8, DataType.UNSIGNED16: 16,
         DataType.UNSIGNED32: 32, DataType.UNSIGNED64: 64, **_SIGNED_BITS}
_NODE_ID_OBJECTS = {(0x1014, 0), (0x1200, 1), (0x1200, 2)}
_COB_BASES = {0x80, 0x180, 0x200, 0x280, 0x300, 0x380, 0x400, 0x480, 0x500,
              0x580, 0x600}
_FIXED_NAMES = {
    0x1000: "Device type", 0x1001: "Error register", 0x1003: "Pre-defined error field",
    0x1005: "COB-ID SYNC", 0x1008: "Manufacturer device name",
    0x1010: "Store parameters", 0x1011: "Restore default parameters",
    0x1014: "COB-ID EMCY", 0x1015: "Inhibit time EMCY", 0x1017: "Producer heartbeat time",
    0x1018: "Identity object", 0x1200: "SDO server parameter",
}


def _node_id_relative(var: Variable, value: Any) -> bool:
    if not isinstance(value, int) or isinstance(value, bool):
        return False
    pdo_comm = 0x1400 <= var.index < 0x1600 or 0x1800 <= var.index < 0x1A00
    return (var.index, var.sub) in _NODE_ID_OBJECTS or (pdo_comm and var.sub == 1)


def _text(value: str) -> str:
    if any(c in value for c in ";\r\n"):
        raise ValueError(f"cannot represent {value!r} in an EDS file")
    return value


def _number(var: Variable, value: Any) -> str:
    if var.dtype in _SIGNED_BITS:
        return str(int(value))
    return f"0x{int(value):X}"


def _default(var: Variable, value: Any, node_id: int) -> str:
    if var.dtype == DataType.VISIBLE_STRING:
        return _text(value if isinstance(value, str) else bytes(value).decode("ascii"))
    if var.dtype == DataType.OCTET_STRING:
        return bytes(value).hex()
    if var.dtype == DataType.REAL32:
        return repr(float(value))
    if _node_id_relative(var, value):
        base = (value & 0x7FF) - node_id
        if base in _COB_BASES:
            return f"$NODEID+0x{(value & ~0x7FF) | base:X}"
    return _number(var, value)


def _limit(var: Variable, value: float) -> str:
    if var.dtype in _SIGNED_BITS:  # the importer reads signed limits as two's complement
        bits = _SIGNED_BITS[var.dtype]
        return f"0x{int(value) & ((1 << bits) - 1):X}"
    if var.dtype == DataType.REAL32:
        return repr(float(value))
    return f"0x{int(value):X}"


def _object_name(index: int, subs: list[Variable]) -> str:
    if index in _FIXED_NAMES:
        return _FIXED_NAMES[index]
    for first, last, label in ((0x1400, 0x15FF, "Receive PDO communication parameter"),
                               (0x1600, 0x17FF, "Receive PDO mapping parameter"),
                               (0x1800, 0x19FF, "Transmit PDO communication parameter"),
                               (0x1A00, 0x1BFF, "Transmit PDO mapping parameter")):
        if first <= index <= last:
            return label
    if len(subs) == 1:
        return subs[0].name
    return f"Object 0x{index:04X}"


def export_eds(node: "Node", path: Path | str | None = None,
               created: datetime | None = None) -> str:
    """Return the EDS text for ``node`` (and write it to ``path`` if given)."""
    defaults = node._defaults
    groups: dict[int, list[Variable]] = {}
    for var in node.od.entries():
        groups.setdefault(var.index, []).append(var)
    for subs in groups.values():
        subs.sort(key=lambda v: v.sub)

    def default_of(var: Variable) -> Any:
        return defaults.get((var.index, var.sub), var.value)

    rx = sum(1 for i in groups if 0x1400 <= i < 0x1600)
    tx = sum(1 for i in groups if 0x1800 <= i < 0x1A00)
    ident = lambda sub: defaults.get((0x1018, sub), 0)  # noqa: E731

    out: list[str] = [HEADER, "", "[FileInfo]", f"FileName={_text(node.name)}.eds",
                      "FileVersion=1", "FileRevision=0", "EDSVersion=4.0",
                      f"Description=Simulated CANopen device {_text(node.name)}",
                      "CreatedBy=canopen-sim"]
    if created is not None:
        out += [f"CreationTime={created:%I:%M%p}", f"CreationDate={created:%m-%d-%Y}"]
    out += ["", "[DeviceInfo]", "VendorName=canopen-sim", f"VendorNumber={ident(1)}",
            f"ProductName={_text(node.name)}", f"ProductNumber={ident(2)}",
            f"RevisionNumber={ident(3)}"]
    out += [f"BaudRate_{r}={int(r in (125, 250, 500, 1000))}"
            for r in (10, 20, 50, 125, 250, 500, 800, 1000)]
    out += ["SimpleBootUpMaster=0", "SimpleBootUpSlave=1", "Granularity=8",
            "DynamicChannelsSupported=0", "GroupMessaging=0",
            f"NrOfRXPDO={rx}", f"NrOfTXPDO={tx}", "LSS_Supported=0", ""]

    lists = {"MandatoryObjects": [], "OptionalObjects": [], "ManufacturerObjects": []}
    for index in sorted(groups):
        if index in _MANDATORY:
            lists["MandatoryObjects"].append(index)
        elif 0x2000 <= index < 0x6000:
            lists["ManufacturerObjects"].append(index)
        else:
            lists["OptionalObjects"].append(index)
    for section, indexes in lists.items():
        out.append(f"[{section}]")
        out.append(f"SupportedObjects={len(indexes)}")
        out += [f"{n}=0x{i:04X}" for n, i in enumerate(indexes, 1)]
        out.append("")

    def body(var: Variable) -> list[str]:
        lines = [f"DataType=0x{int(var.dtype):04X}", f"AccessType={var.access}",
                 f"DefaultValue={_default(var, default_of(var), node.node_id)}",
                 f"PDOMapping={int(var.pdo_mappable)}"]
        if var.low is not None:
            lines.append(f"LowLimit={_limit(var, var.low)}")
        if var.high is not None:
            lines.append(f"HighLimit={_limit(var, var.high)}")
        return lines

    for index in sorted(groups):
        subs = groups[index]
        if len(subs) == 1 and subs[0].sub == 0:
            out += [f"[{index:04X}]", f"ParameterName={_text(subs[0].name)}",
                    "ObjectType=0x7", *body(subs[0]), ""]
            continue
        out += [f"[{index:04X}]", f"ParameterName={_text(_object_name(index, subs))}",
                "ObjectType=0x9", f"SubNumber={len(subs)}", ""]
        for var in subs:
            out += [f"[{index:04X}sub{var.sub:X}]", f"ParameterName={_text(var.name)}",
                    "ObjectType=0x7", *body(var), ""]

    text = "\n".join(out)
    if path is not None:
        Path(path).write_text(text, encoding="utf-8")
    return text
